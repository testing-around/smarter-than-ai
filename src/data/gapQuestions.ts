import type { Question } from '../types';

function q(
  partial: Pick<
    Question,
    'question_id' | 'category' | 'subcategory' | 'difficulty' | 'question_type' | 'question' | 'choices' | 'correct_answer' | 'explanation'
  > & Partial<Question>,
): Question {
  return {
    grade_min: partial.difficulty <= 3 ? 1 : 3,
    grade_max: partial.difficulty >= 8 ? 12 : 8,
    time_limit_seconds: partial.question_type === 'BOSS' ? 20 : 15,
    base_points: partial.question_type === 'BOSS' ? 150 : 100,
    speed_bonus: true,
    steal_allowed: true,
    source_verified: true,
    active: true,
    quality_score: 0.88,
    ...partial,
    accepted_answers: partial.accepted_answers ?? [partial.correct_answer],
  };
}

