import type { MasterCategory, Question } from '../types';

function mc(input: {
  id: string;
  grade: number;
  category: MasterCategory;
  subcategory: string;
  question: string;
  correct: string;
  distractors: [string, string, string];
  aliases?: string[];
  explanation: string;
}): Question {
  const raw = [input.correct, ...input.distractors];
  const rotate = (input.grade + input.id.length) % raw.length;
  const choices = [...raw.slice(rotate), ...raw.slice(0, rotate)];
  return {
    question_id: input.id,
    category: input.category,
    subcategory: input.subcategory,
    difficulty: Math.min(10, Math.max(1, input.grade)),
    grade_min: input.grade,
    grade_max: Math.min(10, input.grade + 1),
    question_type: 'MULTIPLE_CHOICE',
    question: input.question,
    choices,
    correct_answer: input.correct,
    accepted_answers: [input.correct, ...(input.aliases ?? [])],
    explanation: input.explanation,
    time_limit_seconds: 15,
    base_points: 100,
    speed_bonus: true,
    steal_allowed: true,
    source_verified: true,
    active: true,
    quality_score: 0.92,
  };
}

